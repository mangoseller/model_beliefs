"""Convert downloaded branching batch outputs into the released response files.

Reads ``COLLECTION_DIR/branching/<experiment>/<stage>/`` (record maps and
``outputs/<model>/*.jsonl.out``; see ``collect``) and writes one compact file
per experiment, stage, and model::

    <out>/<experiment>/<stage>/<model>.jsonl

Prompts and replayed prefixes are not repeated: they are regenerated by
``prompts`` and joined through the record IDs.  Every line has the record-map
fields

    initial    record_id, model_alias, model_id, domain, instance_id,
               branch_id + replicate (behavior) | prefix_id + prefix_replicate (probability)
    followups  the same, plus [probability_branch_id, probability_replicate]
               (probability), prompt_variant, task_id, prompt_id, initial_record_id

followed by the response: ``ok``, ``stop_reason``, ``usage`` (inputTokens,
outputTokens, totalTokens), ``error``, and ``output_text`` -- the single text
block of the assistant message, verbatim (follow-ups replay it unchanged).
Lines follow record-map order.  Follow-ups to tasks outside the 16 analysed
outputs of a domain are skipped.

Usage::

    python -m latent_beliefs.branching.materialize   # -> BUILD_DIR/responses/branching
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from latent_beliefs.branching.design import (
    BRANCHING_COLLECTION_DIR,
    CASES_PATH,
    EXPERIMENTS,
    MODELS,
    STAGES,
    Experiment,
    read_jsonl,
    response_path,
    write_jsonl,
)
from latent_beliefs.branching.prompts import load_cases
from latent_beliefs.config import MATERIALIZED_DIR
from latent_beliefs.models import BEDROCK_MODEL_IDS

USAGE_FIELDS = ("inputTokens", "outputTokens", "totalTokens")


def response_fields(raw: dict[str, Any]) -> dict[str, Any]:
    ok = "error" not in raw and "modelOutput" in raw
    if not ok:
        return {"ok": False, "stop_reason": None, "usage": {}, "error": raw.get("error"), "output_text": ""}
    output = raw["modelOutput"]
    blocks = [
        {key: value for key, value in block.items() if value is not None}
        for block in output["output"]["message"]["content"]
    ]
    if len(blocks) != 1 or list(blocks[0]) != ["text"]:
        raise ValueError(f"{raw['recordId']}: expected one text block, found {blocks}")
    usage = output.get("usage") or {}
    return {
        "ok": True,
        "stop_reason": output.get("stopReason"),
        "usage": {key: usage.get(key) for key in USAGE_FIELDS},
        "error": None,
        "output_text": blocks[0]["text"],
    }


def materialize(
    experiment: Experiment,
    stage: str,
    model: str,
    stage_dir: Path,
    analysed_variants: dict[str, set[str]],
    out: Path,
) -> None:
    if stage == "initial":
        record_map = list(read_jsonl(stage_dir / "record_map.jsonl"))
    else:
        record_map = [
            row
            for row in read_jsonl(stage_dir / f"record_map_{model}.jsonl")
            if row["prompt_variant"] in analysed_variants[row["domain"]]
        ]
    raw_by_id: dict[str, dict[str, Any]] = {}
    for path in sorted((stage_dir / "outputs" / model).glob("*.jsonl.out")):
        for raw in read_jsonl(path):
            raw_by_id[str(raw["recordId"])] = raw
    if not raw_by_id:
        raise FileNotFoundError(f"No outputs in {stage_dir / 'outputs' / model}")

    rows, missing = [], 0
    for mapped in record_map:
        raw = raw_by_id.get(mapped["record_id"])
        if raw is None:
            missing += 1
            continue
        metadata = {
            key: value
            for key, value in mapped.items()
            if key not in {"record_id", "model_alias", "model_id", "initial_prompt_sha256"}
        }
        rows.append(
            {
                "record_id": mapped["record_id"],
                "model_alias": model,
                "model_id": BEDROCK_MODEL_IDS[model],
                **metadata,
                **response_fields(raw),
            }
        )
    path = response_path(out, experiment.key, stage, model)
    write_jsonl(path, rows)
    note = f", {missing} missing" if missing else ""
    print(f"{experiment.key}/{stage}/{model}: {len(rows)} responses{note} ({path.stat().st_size} bytes)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--stages", nargs="+", choices=STAGES, default=list(STAGES))
    parser.add_argument("--experiments", nargs="+", choices=list(EXPERIMENTS), default=list(EXPERIMENTS))
    parser.add_argument("--cases", type=Path, default=CASES_PATH)
    parser.add_argument("--collection-dir", type=Path, default=BRANCHING_COLLECTION_DIR)
    parser.add_argument("--out", type=Path, default=MATERIALIZED_DIR / "branching")
    args = parser.parse_args()
    analysed_variants: dict[str, set[str]] = {}
    for case in load_cases(args.cases):
        analysed_variants.setdefault(case["domain"], set()).update(
            task["prompt_variant"] for task in case["followups"]
        )
    for key in args.experiments:
        for stage in args.stages:
            for model in MODELS:
                materialize(
                    EXPERIMENTS[key],
                    stage,
                    model,
                    args.collection_dir / key / stage,
                    analysed_variants,
                    args.out,
                )


if __name__ == "__main__":
    main()
